#!/usr/bin/env python3
"""Generate `docs/TRACE.md` — the tool -> module -> codes -> examples link table.

Derived from the registry and the filesystem, so it cannot drift: a test fails
if the committed file and this generator disagree. This is the "manage the
code/artifact/docs links" view done the cheap way — a generated table and a
guard, not a database.

    python scripts/make_trace.py   # writes docs/TRACE.md
"""

from __future__ import annotations

import pathlib

from gxkit.codes import CODEBOOK
from gxkit.registry import TOOLS

ROOT = pathlib.Path(__file__).resolve().parents[1]
OUT = ROOT / "docs" / "TRACE.md"


def _examples(tool: str) -> str:
    names = sorted(p.name for p in (ROOT / "packages" / tool / "examples").glob("*.py"))
    return ", ".join(f"`{name}`" for name in names) if names else "—"


def build() -> str:
    lines = [
        "# Traceability",
        "",
        "Generated by `scripts/make_trace.py` — **do not edit by hand**; a test fails",
        "if this file and the generator disagree.",
        "",
        "Each tool is one package, one `tool.py` module, one group in `gxkit.codes`, and",
        "a set of example artifacts. `reads` is the file suffixes the tool accepts,",
        "declared in `gxkit.registry` and checked against the loader. The invariant",
        "checks (that every check can fail, that the docs agree) live in",
        "`packages/gxkit/tests/`.",
        "",
        "| tool | inspects | reads | module | codes (#) | examples |",
        "| --- | --- | --- | --- | --- | --- |",
    ]
    for spec in TOOLS:
        codes = CODEBOOK.get(spec.name, {})
        reads = ", ".join(f"`{suffix}`" for suffix in spec.reads)
        lines.append(
            f"| `{spec.name}` | {spec.inspects} | {reads} | `{spec.module}` "
            f"| {len(codes)} | {_examples(spec.name)} |"
        )
    lines.append("")
    return "\n".join(lines)


def main() -> None:
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(build(), encoding="utf-8")
    print(f"wrote {OUT} ({OUT.stat().st_size} bytes)")


if __name__ == "__main__":
    main()
