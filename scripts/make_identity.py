#!/usr/bin/env python3
"""Generate `docs/IDENTITY.md` — the error findings that cannot be told apart.

A finding is compared by its baseline fingerprint: its code, and either an
explicit relationship `identity` or the display location. When an error finding
carries neither a target nor an identity, two of them in one artifact share a
fingerprint, so *replacing* one with another reads as unchanged debt — the gate
passes on a change.

This lists those sites, from the source, so the debt is countable and a fix is
visible. A test fails when the file and the generator disagree, and fails again
when the number of sites grows: lower the limit in the test as sites are fixed,
and never raise it without saying why.

    python scripts/make_identity.py   # writes docs/IDENTITY.md
"""

from __future__ import annotations

import ast
import pathlib

ROOT = pathlib.Path(__file__).resolve().parents[1]
OUT = ROOT / "docs" / "IDENTITY.md"

#: Findings that carry no location and cannot occur twice in one artifact, with
#: the guard that makes that true. Each was read before being written here: an
#: entry says *where* the single `if`/`except` is, so a second one appearing later
#: is a change to the code, not a change to this table. A site that gains a
#: `target` or a `label` leaves this table on the next generation — the guard
#: refuses an entry that is no longer a site.
UNIQUE_PER_ARTIFACT: dict[tuple[str, str], str] = {
    ("flowgx", "no-start"): "one `if` decides the machine has no start state",
    ("flowgx", "no-accept"): "one `if` decides nothing is accepting",
    ("levelgx", "no-spawn"): "one `if spawn is None` reads the single spawn cell",
    ("levelgx", "no-goal"): "one `if goal is None` reads the single goal cell",
    ("protogx", "no-start"): "one `if` decides the protocol has no start state",
    ("protogx", "no-terminal"): "one `if not accepting` decides there is no terminal state",
    ("framegx", "missing-file"): "one `if not media.exists()` decides the artifact is unreadable",
    ("framegx", "probe-error"): "one `except` around the single probe of the artifact",
    ("framegx", "no-frames"): "one `if frames.shape[0] == 0` on the sampled clip",
    ("framegx", "all-black"): "one `if max(means) < level` over the whole clip",
    ("shadergx", "bad-size"): "one `if` on the declared output size",
    ("shadergx", "compile-error"): "one `except` around the single compile of the shader",
    ("shadergx", "black-output"): "one `if` on the single rendered frame",
    ("shadergx", "nan-output"): "one `if not isfinite(...).all()` on the rendered output",
    (
        "checkgx",
        "no-checks",
    ): "one `if not declared` branch fires only when the registry declares nothing",
}


def sites() -> dict[str, list[str]]:
    """tool -> error codes whose findings have neither a target nor an identity."""
    found: dict[str, list[str]] = {}
    for path in sorted((ROOT / "packages").glob("*/src/*/checks.py")):
        tool = path.parts[-2]  # packages/<tool>/src/<tool>/checks.py
        tree = ast.parse(path.read_bytes(), filename=str(path))
        for node in ast.walk(tree):
            if not isinstance(node, ast.Call):
                continue
            name = getattr(node.func, "attr", "") or getattr(node.func, "id", "")
            if name not in {"Problem", "_problem"}:
                continue
            args = node.args
            if not args or not isinstance(args[0], ast.Name) or args[0].id != "ERROR":
                continue
            if len(args) < 2 or not isinstance(args[1], ast.Constant):
                continue
            # `fingerprint()` compares a finding by its identity, or by its
            # display location — `target` *and* `label`. Only a finding with none
            # of the three is indistinguishable from a sibling, so `label` counts
            # here: the first version of this script ignored it and listed sites
            # that were already fine.
            keywords = {keyword.arg for keyword in node.keywords}
            if {"identity", "target", "label"} & keywords:
                continue
            code = str(args[1].value)
            codes = found.setdefault(tool, [])
            if code not in codes:
                codes.append(code)
    return {tool: sorted(codes) for tool, codes in sorted(found.items())}


def debt() -> dict[str, list[str]]:
    """Sites that carry no location *and* can occur more than once: real debt."""
    found: dict[str, list[str]] = {}
    for tool, codes in sites().items():
        remaining = [code for code in codes if (tool, code) not in UNIQUE_PER_ARTIFACT]
        if remaining:
            found[tool] = remaining
    return found


def build() -> str:
    found = sites()
    owing = debt()
    total = sum(len(codes) for codes in found.values())
    lines = [
        "# Error findings with no distinguishing location",
        "",
        "Generated by `scripts/make_identity.py` — **do not edit by hand**; a test fails",
        "if this file and the generator disagree.",
        "",
        "`fingerprint()` compares a finding by an explicit relationship `identity`, or by",
        "its display location (`target` *and* `label`). A finding with none of the three is",
        "compared by its code alone, so two of them in one artifact share a fingerprint and",
        "replacing one with another reads as unchanged baseline debt.",
        "",
        f"**{total} such findings; {len(owing) and sum(len(c) for c in owing.values())}"
        f" of them can occur more than once.**",
        "",
        "## Can occur more than once — debt",
        "",
    ]
    if owing:
        lines += ["| tool | codes |", "| --- | --- |"]
        for tool, codes in owing.items():
            lines.append(f"| `{tool}` | {', '.join(f'`{code}`' for code in codes)} |")
    else:
        lines.append(
            "None. Every finding that can repeat carries a relationship identity or a"
            " location, so a replaced relationship is new debt rather than unchanged debt."
        )
    lines += [
        "",
        "## Cannot occur twice in one artifact",
        "",
        "Each is a single `if`/`except` per inspection. The reason is checked against the",
        "source: an entry that gains a `target` or a `label` leaves this table on the next",
        "generation, and the guard refuses an entry that is no longer a site.",
        "",
        "| tool | code | why it can only happen once |",
        "| --- | --- | --- |",
    ]
    for (tool, code), reason in sorted(UNIQUE_PER_ARTIFACT.items()):
        lines.append(f"| `{tool}` | `{code}` | {reason} |")
    lines.append("")
    return "\n".join(lines)


def main() -> None:
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(build(), encoding="utf-8")
    print(f"wrote {OUT} ({sum(len(c) for c in sites().values())} sites)")


if __name__ == "__main__":
    main()
