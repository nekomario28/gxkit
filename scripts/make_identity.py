#!/usr/bin/env python3
"""Generate `docs/IDENTITY.md` — the error findings that cannot be told apart.

A finding is compared by its baseline fingerprint: its code, and either an
explicit relationship `identity` or the display location. When an error finding
carries neither a target nor an identity, two of them in one artifact share a
fingerprint, so *replacing* one with another reads as unchanged debt — the gate
passes on a change.

This lists those sites, from the source, so the debt is countable and a fix is
visible. A test fails when the file and the generator disagree, and fails again
when the number of sites grows: lower the limit in the test as sites are fixed,
and never raise it without saying why.

    python scripts/make_identity.py   # writes docs/IDENTITY.md
"""

from __future__ import annotations

import ast
import pathlib

ROOT = pathlib.Path(__file__).resolve().parents[1]
OUT = ROOT / "docs" / "IDENTITY.md"


def sites() -> dict[str, list[str]]:
    """tool -> error codes whose findings have neither a target nor an identity."""
    found: dict[str, list[str]] = {}
    for path in sorted((ROOT / "packages").glob("*/src/*/checks.py")):
        tool = path.parts[-2]  # packages/<tool>/src/<tool>/checks.py
        tree = ast.parse(path.read_bytes(), filename=str(path))
        for node in ast.walk(tree):
            if not isinstance(node, ast.Call):
                continue
            name = getattr(node.func, "attr", "") or getattr(node.func, "id", "")
            if name not in {"Problem", "_problem"}:
                continue
            args = node.args
            if not args or not isinstance(args[0], ast.Name) or args[0].id != "ERROR":
                continue
            if len(args) < 2 or not isinstance(args[1], ast.Constant):
                continue
            keywords = {keyword.arg for keyword in node.keywords}
            if {"identity", "target"} & keywords:
                continue
            code = str(args[1].value)
            codes = found.setdefault(tool, [])
            if code not in codes:
                codes.append(code)
    return {tool: sorted(codes) for tool, codes in sorted(found.items())}


def build() -> str:
    found = sites()
    total = sum(len(codes) for codes in found.values())
    lines = [
        "# Error findings with no distinguishing location",
        "",
        "Generated by `scripts/make_identity.py` — **do not edit by hand**; a test fails",
        "if this file and the generator disagree.",
        "",
        "Each finding below is compared by its code alone, because it carries neither a",
        "`target` nor an `identity`. Two of them in one artifact therefore share a",
        "fingerprint, and replacing one with another reads as unchanged baseline debt.",
        "The list is a ratchet: fix a site and lower the limit in",
        "`test_identity_inventory.py`; do not raise it without saying why.",
        "",
        f"**{total} sites.**",
        "",
        "| tool | codes |",
        "| --- | --- |",
    ]
    for tool, codes in found.items():
        lines.append(f"| `{tool}` | {', '.join(f'`{code}`' for code in codes)} |")
    lines.append("")
    return "\n".join(lines)


def main() -> None:
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(build(), encoding="utf-8")
    print(f"wrote {OUT} ({sum(len(c) for c in sites().values())} sites)")


if __name__ == "__main__":
    main()
